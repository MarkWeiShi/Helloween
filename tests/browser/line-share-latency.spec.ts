import {test,expect} from '@playwright/test';
test.use({baseURL:process.env.SHARE_TEST_ORIGIN||'http://127.0.0.1:5187'});
test('LINE editor is usable within four seconds while optional artwork never responds',async({page})=>{
 await page.route('**/api/social/config',r=>r.fulfill({json:{lineLiffId:'test-liff',origin:'http://127.0.0.1:5187'}}));
 await page.route('**/api/invites/test-invite',r=>r.fulfill({json:{spiritId:'jiangshi',expired:false}}));
 await page.route('**/api/session',r=>r.fulfill({json:{player:{initialized:true,name:'Tester'}}}));
 await page.route('https://static.line-scdn.net/**',r=>r.fulfill({contentType:'application/javascript',body:'window.sent=[];window.liff={init:async()=>{},isLoggedIn:()=>true,isApiAvailable:()=>true,shareTargetPicker:async m=>{window.sent.push(m);return {status:"success"}}};'}));
 await page.route('**/art/share-animations/manifest.json',r=>r.fulfill({json:{characters:{jiangshi:{apng:'/slow-art.png',bytes:100,width:100,height:100,frames:2}}}}));
 await page.route('**/slow-art.png',()=>new Promise(()=>{}));
 const start=Date.now();
 await page.goto('/line-share.html?invite=test-invite&lang=en',{waitUntil:'domcontentloaded'});
 await expect(page.locator('#choose')).toBeEnabled({timeout:Math.max(1,4000-(Date.now()-start))});
 console.log('LINE editor ready ms',Date.now()-start);
 await page.locator('#message').fill('Keep this message');
 expect(await page.evaluate(()=>(window as any).sent.length)).toBe(0);
 await page.locator('#choose').click();
 await expect(page.locator('[role=status]')).toHaveText('Card sent.');
 expect(await page.evaluate(()=>(window as any).sent[0][0].altText)).toBe('Keep this message');
});
test('LINE starts SDK and config together and keeps the draft when optional details arrive',async({page})=>{
 let releaseConfig!:()=>void,releaseDetails!:()=>void;
 const configGate=new Promise<void>(r=>releaseConfig=r),detailsGate=new Promise<void>(r=>releaseDetails=r);
 let sdkRequested=false;
 await page.route('**/api/social/config',async r=>{await configGate;await r.fulfill({json:{lineLiffId:'test-liff',origin:'http://127.0.0.1:5187'}});});
 await page.route('**/api/invites/test-invite',r=>r.fulfill({json:{spiritId:'jiangshi',expired:false}}));
 await page.route('**/api/session',r=>r.fulfill({json:{player:{initialized:true,name:'Tester'}}}));
 await page.route('https://static.line-scdn.net/**',r=>{sdkRequested=true;return r.fulfill({contentType:'application/javascript',body:'window.sent=[];window.liff={init:async()=>{},isLoggedIn:()=>true,isApiAvailable:()=>true,shareTargetPicker:async m=>{window.sent.push(m);return {status:"success"}}};'});});
 await page.route('**/art/share-animations/manifest.json',r=>r.fulfill({json:{characters:{}}}));
 await page.route('**/art/x-cards/manifest.json',async r=>{await detailsGate;await r.fulfill({json:{characters:{jiangshi:{nativeName:'Updated name',name:'Jiangshi',localized:{en:{compactCulture:'Updated culture'}}}}}});});
 await page.goto('/line-share.html?invite=test-invite&lang=en',{waitUntil:'domcontentloaded'});
 await expect.poll(()=>sdkRequested).toBe(true);releaseConfig();
 await expect(page.locator('#choose')).toBeEnabled();
 await page.locator('#message').fill('My preserved draft');releaseDetails();
 await expect(page.locator('.card h2')).toHaveText('Updated name');
 await expect(page.locator('#message')).toHaveValue('My preserved draft');
 expect(await page.evaluate(()=>(window as any).sent.length)).toBe(0);
 await page.locator('#choose').click();
 expect(await page.evaluate(()=>(window as any).sent[0][0].altText)).toBe('My preserved draft');
});
